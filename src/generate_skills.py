# ------------------------------------------------------------
# Создание справочника
# ------------------------------------------------------------

def generate_skills():
    """
    Создает список навыков с ID и названием.
    """

    skills = []

    for i, skill_name in enumerate(SKILL_NAMES):
        skill_id = SKILL_START_ID + i

        skills.append({
            "skill_id": skill_id,
            "skill_name": skill_name
        })

    return skills


# ------------------------------------------------------------
# Генерация данных
# ------------------------------------------------------------

skills = generate_skills()


# ------------------------------------------------------------
# Сохранение в CSV
# ------------------------------------------------------------

with open(
    OUTPUT_FILE,
    "w",
    newline="",
    encoding="utf-8-sig"
) as f:

    writer = csv.DictWriter(
        f,
        fieldnames=["skill_id", "skill_name"],
        delimiter=";"
    )

    writer.writeheader()
    writer.writerows(skills)


# ------------------------------------------------------------
